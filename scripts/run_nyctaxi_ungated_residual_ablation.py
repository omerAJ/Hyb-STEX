    parser.add_argument("--output-dir", default=str(root / "nyctaxi_ungated_residual_results"))
    parser.add_argument("--seeds", default="1,2,3")
    parser.add_argument("--device", default="auto", choices=["auto", "cuda", "cpu"])
    parser.add_argument("--event-percentile", default=90.0, type=float)
    parser.add_argument(
        "--event-threshold-source",
        default="file",
        choices=EVENT_THRESHOLD_SOURCE_CHOICES,
        help=(
            "Event-label threshold source. 'file' uses saved evs_90 arrays; "
            "'train' regenerates paper-correct labels in memory; "
            "'split' reproduces the old notebook rule."
        ),
    )
    parser.add_argument("--max-epochs", default=None, type=int, help="Optional smoke-test epoch cap per phase.")
    parser.add_argument(
        "--baseline-results",
        default="auto",
        help="Path to previous drift experiment results.csv, 'auto', or 'none'.",
    )
    parser.add_argument("--preflight-only", action="store_true")
    args = parser.parse_args()

    data_dir = Path(args.data_dir).resolve()
    config_path = Path(args.config).resolve()
    device = args.device
    if device == "auto":
        device = "cuda" if torch.cuda.is_available() else "cpu"

    preflight_environment(data_dir, device)
    add_repo_to_path(root)
    configs = load_config(config_path)
    preflight_model(configs, data_dir, device, args.event_percentile, args.event_threshold_source)
    if args.preflight_only:
        print("Preflight complete. No training was run.")
        return 0

    baseline_path: Path | None
    if args.baseline_results == "auto":
        baseline_path = find_latest_baseline(root)
    elif args.baseline_results.lower() == "none":
        baseline_path = None
    else:
        baseline_path = Path(args.baseline_results).resolve()
    if baseline_path is not None:
        print(f"Baseline comparison file: {baseline_path}")
    else:
        print("No baseline comparison file found/provided.")

    output_dir = Path(args.output_dir).resolve() / datetime.now().strftime("%Y%m%d-%H%M%S")
    output_dir.mkdir(parents=True, exist_ok=True)

    rows: list[dict[str, Any]] = []
    for seed in parse_seed_list(args.seeds):
        print(f"\n=== NYCTaxi ungated_residual seed={seed} device={device} ===")
        run_rows = run_one(
            configs=configs,
            data_dir=data_dir,
            output_dir=output_dir,
            seed=seed,
            device=device,
            event_percentile=args.event_percentile,
            event_threshold_source=args.event_threshold_source,
            max_epochs=args.max_epochs,
        )
        rows.extend(run_rows)
        write_outputs(output_dir, rows, args, baseline_path)
        print(
            markdown_table(
                run_rows,
                ["seed", "flow", "residual_mae", "residual_eee", "base_mae", "base_eee"],
            )
        )

    write_outputs(output_dir, rows, args, baseline_path)
    print(f"\nSaved results to: {output_dir}")
    print((output_dir / "results.md").read_text(encoding="utf-8"))
    return 0


